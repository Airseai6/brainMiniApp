// 每日一练 / 随机体验：按日期稳定抽 3 个关卡；随机体验排除当前关卡。
function hashStr(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function todayKey(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}`;
}

function dailyKeys(keys, dateStr, count = 3) {
  const rnd = mulberry32(hashStr('daily-practice|' + dateStr));
  const pool = keys.slice();
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(count, pool.length));
}

function randomKey(keys, exclude) {
  const pool = keys.filter((k) => k !== exclude);
  return pool[Math.floor(Math.random() * pool.length)];
}

module.exports = { hashStr, todayKey, dailyKeys, randomKey };
